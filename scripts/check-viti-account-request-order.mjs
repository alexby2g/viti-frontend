import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
const root=process.cwd()
const read=(f)=>fs.readFileSync(path.resolve(root,f),'utf8')
const account=read('../backend/app/Http/Controllers/ClientAuthController.php')
const publicApp=read('../backend/app/Http/Controllers/PublicApplicationController.php')
const request=read('src/pages/PublicSolicitudStartPage.vue')
const register=read('src/pages/ClientRegisterPage.vue')
const router=read('src/router/index.js')
const routes=read('src/router/routes.js')
const login=read('src/pages/LoginPage.vue')
const hub=read('src/pages/ClientHubPage.vue')
const layout=read('src/layouts/MainLayout.vue')
assert.ok(account.includes("whereRaw('LOWER(correo) = ?'"),'Registro debe buscar prospecto por correo')
assert.ok(account.includes('solicitudes_vinculadas'),'Registro debe informar solicitudes vinculadas')
assert.ok(!account.includes("'unique:clientes,correo'"),'Correo de prospecto no debe bloquear una cuenta')
assert.ok(!publicApp.includes('Este responsable ya tiene una cuenta VITI. Inicia sesión para enviar una nueva solicitud.'),'Cuenta existente no debe bloquear solicitud pública')
assert.ok(publicApp.includes("'cuenta_existente' => $cliente->usuario()->exists()"),'Solicitud debe informar si ya existe cuenta')
// Orden vigente: ver VITI es libre; para solicitar se inicia sesión (o se crea la cuenta) y se elige el pago.
assert.ok(publicApp.includes('Inicia sesión o crea tu cuenta VITI para enviar tu solicitud.'),'El envío anónimo debe pedir sesión')
assert.ok(routes.includes("path: '/solicitud', component: AuthLayout, meta: { requiresAuth:true, clientOnly:true }"),'La solicitud debe exigir cuenta de cliente')
assert.ok(request.includes("api.post('/mi/solicitud/enviar'"),'La solicitud debe enviarse con la cuenta del cliente')
assert.ok(request.includes('¿Cómo pagarás la implementación?'),'La solicitud debe pedir la forma de pago')
assert.ok(login.includes("requested.startsWith('/solicitud')"),'El login debe volver a la solicitud')
assert.ok(register.includes("requested.startsWith('/solicitud')"),'El registro debe volver a la solicitud')
assert.ok(router.includes("path:'/demo', component:() => import('../layouts/AuthLayout.vue')"),'Demo debe vivir dentro de QLayout')
assert.ok(router.includes('scrollBehavior'),'Router debe controlar el scroll')
assert.ok(hub.includes("window.location.href = '/solicitud'"),'Portal cliente debe usar solicitud oficial')
assert.ok(layout.includes("window.location.href = '/solicitud'"),'Menú cliente debe usar solicitud oficial')
console.log('VITI account/request order audit: PASS')
